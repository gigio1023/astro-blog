import { existsSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { join, relative, sep } from 'node:path'

const BLOG_DIR = join(process.cwd(), 'src/content/blog')
const REDIRECTS_PATH = join(process.cwd(), 'public/_redirects')

function normalizePath(pathname) {
  return pathname.split(sep).join('/')
}

function encodeRoute(pathname) {
  return pathname
    .split('/')
    .map((part) => (part ? encodeURIComponent(part) : part))
    .join('/')
}

function walkPostDirs(dir, result = []) {
  for (const entry of readdirSync(dir)) {
    const fullPath = join(dir, entry)

    if (!statSync(fullPath).isDirectory()) {
      continue
    }

    const files = readdirSync(fullPath)
    const hasPostEntry = files.some((file) =>
      /^index(?:\.(?:en|it))?\.(?:md|mdx)$/.test(file),
    )

    if (hasPostEntry) {
      result.push(normalizePath(relative(BLOG_DIR, fullPath)))
    }

    walkPostDirs(fullPath, result)
  }

  return result
}

if (!existsSync(BLOG_DIR)) {
  throw new Error(`Blog content directory not found: ${BLOG_DIR}`)
}

const blogSlugs = walkPostDirs(BLOG_DIR).sort()
const staticDefaultLangRedirects = blogSlugs.flatMap((slug) => {
  const source = encodeRoute(`/blog/${slug}`)
  const destination = encodeRoute(`/blog/en/${slug}/`)

  return [`${source} ${destination} 301`, `${source}/ ${destination} 301`]
})

const lines = [
  '# Cloudflare Pages static redirects.',
  '# Generated by scripts/generate-redirects.mjs.',
  '# Keep this file in public/ so Astro copies it into dist.',
  '',
  '# Known slashless route roots.',
  '/blog /blog/ 301',
  '/blog/ko /blog/ko/ 301',
  '/blog/en /blog/en/ 301',
  '/blog/it /blog/it/ 301',
  '/tags /tags/ 301',
  '/authors /authors/ 301',
  '',
  '# Old default-language blog URLs generated from current blog slugs.',
  ...staticDefaultLangRedirects,
  '',
  '# Dynamic slash normalization.',
  '/blog/ko/:slug /blog/ko/:slug/ 301',
  '/blog/en/:slug /blog/en/:slug/ 301',
  '/blog/it/:slug /blog/it/:slug/ 301',
  '/tags/:tag /tags/:tag/ 301',
  '/authors/:author /authors/:author/ 301',
  '',
  '# Legacy timestamp URLs from previous platforms.',
  '/blog/ko/:slug/:timestamp /blog/ko/:slug/ 301',
  '/blog/en/:slug/:timestamp /blog/en/:slug/ 301',
  '/blog/it/:slug/:timestamp /blog/it/:slug/ 301',
  '/blog/:slug/:timestamp /blog/en/:slug/ 301',
]

writeFileSync(REDIRECTS_PATH, `${lines.join('\n')}\n`)

console.log(
  `Generated ${REDIRECTS_PATH} with ${lines.filter(Boolean).length} lines.`,
)
